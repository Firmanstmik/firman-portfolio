export function detectLang(): Lang {
  const stored = localStorage.getItem('lang')
  if (stored === 'en' || stored === 'id') return stored
  const n = (navigator.language || 'en').toLowerCase()
  return n.startsWith('id') ? 'id' : 'en'
}
